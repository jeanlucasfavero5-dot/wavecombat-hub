-- Cria: pf_clas · pf_clas_membros · pf_clas_pedidos
-- Segurança: igual ao resto do Hub (chave pública do jogo + ID do jogador);
-- as regras de líder/vice são aplicadas pelo jogo. Ajuste as políticas
-- abaixo se um dia o Hub passar a usar autenticação do Supabase.
-- ============================================================

create table if not exists public.pf_clas (
  id          bigint generated by default as identity (start with 100001) primary key,
  nome        text   not null check (char_length(nome) between 3 and 16),
  emblema     text   not null default '🛡️',
  cor         text   not null default '#ff2d7a',
  descricao   text   not null default '',
  anuncio     text   not null default '',
  modo        text   not null default 'pedido' check (modo in ('aberto','pedido','fechado')),
  nivel_min   int    not null default 1,
  lider_id    text   not null,
  lider_nick  text,
  criado_em   timestamptz not null default now()
);
create unique index if not exists pf_clas_nome_uq on public.pf_clas (lower(nome));

create table if not exists public.pf_clas_membros (
  id          bigint generated by default as identity primary key,
  clan_id     bigint not null references public.pf_clas(id) on delete cascade,
  id_jogador  text   not null,
  nick        text,
  cargo       text   not null default 'membro' check (cargo in ('lider','vice','membro')),
  nivel       int    not null default 1,
  pontos      int    not null default 0,
  entrou_em   timestamptz not null default now()
);
-- um jogador só pode estar em um clã
create unique index if not exists pf_clas_membros_jogador_uq on public.pf_clas_membros (id_jogador);
create index        if not exists pf_clas_membros_clan_idx   on public.pf_clas_membros (clan_id);

create table if not exists public.pf_clas_pedidos (
  id          bigint generated by default as identity primary key,
  clan_id     bigint not null references public.pf_clas(id) on delete cascade,
  id_jogador  text   not null,
  nick        text,
  nivel       int    not null default 1,
  criado_em   timestamptz not null default now()
);
create unique index if not exists pf_clas_pedidos_uq      on public.pf_clas_pedidos (clan_id, id_jogador);
create index        if not exists pf_clas_pedidos_jog_idx on public.pf_clas_pedidos (id_jogador);

-- RLS + permissões para a chave pública (anon)
alter table public.pf_clas          enable row level security;
alter table public.pf_clas_membros  enable row level security;
alter table public.pf_clas_pedidos  enable row level security;

drop policy if exists pf_clas_all         on public.pf_clas;
drop policy if exists pf_clas_membros_all on public.pf_clas_membros;
drop policy if exists pf_clas_pedidos_all on public.pf_clas_pedidos;
create policy pf_clas_all         on public.pf_clas         for all to anon, authenticated using (true) with check (true);
create policy pf_clas_membros_all on public.pf_clas_membros for all to anon, authenticated using (true) with check (true);
create policy pf_clas_pedidos_all on public.pf_clas_pedidos for all to anon, authenticated using (true) with check (true);

grant select, insert, update, delete on public.pf_clas, public.pf_clas_membros, public.pf_clas_pedidos to anon, authenticated;

-- atualiza o cache da API do Supabase
notify pgrst, 'reload schema';
